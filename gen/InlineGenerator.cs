using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace RNGTick.Generator;

/// <summary>
/// Writes the hot postfix by flattening <c>TickOffset.Apply</c> and everything it calls.
///
/// <para><b>Why.</b> Measured, a Harmony postfix that calls out to one other method costs about
/// 8 ns per roll more than the same arithmetic written inline, and a second level of calls costs
/// nothing further -- the JIT declines the first inline and that is the whole penalty, whatever
/// <c>AggressiveInlining</c> asks for. Roslyn does not inline, so the only way to have the
/// arithmetic written once and executed flat is to generate the flat copy.</para>
///
/// <para><b>What it supports.</b> Deliberately the narrowest thing that covers this mod rather
/// than a general inliner: static methods marked <c>[Inlinable]</c>, each with a single
/// <c>return</c> as its last statement (or an expression body), called from the body of the one
/// method marked <c>[InlineIntoPostfix]</c>. Anything else is reported as a diagnostic rather
/// than mis-generated, because a source generator that quietly emits the wrong arithmetic is a
/// far worse failure than one that refuses.</para>
/// </summary>
[Generator]
public sealed class InlineGenerator : IIncrementalGenerator
{
    private const string InlinableAttribute = "RNGTick.InlinableAttribute";
    private const string PostfixAttribute = "RNGTick.InlineIntoPostfixAttribute";

    private static readonly DiagnosticDescriptor Unsupported = new(
        "RNGTICK001", "Cannot inline this method",
        "{0}", "RNGTick", DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var inlinable = context.SyntaxProvider.ForAttributeWithMetadataName(
            InlinableAttribute,
            static (node, _) => node is MethodDeclarationSyntax,
            static (ctx, _) => (MethodDeclarationSyntax)ctx.TargetNode).Collect();

        var target = context.SyntaxProvider.ForAttributeWithMetadataName(
            PostfixAttribute,
            static (node, _) => node is MethodDeclarationSyntax,
            static (ctx, _) => (MethodDeclarationSyntax)ctx.TargetNode).Collect();

        context.RegisterSourceOutput(inlinable.Combine(target), static (spc, pair) =>
            Emit(spc, pair.Left, pair.Right));
    }

    private static void Emit(SourceProductionContext spc,
        ImmutableArray<MethodDeclarationSyntax> inlinable,
        ImmutableArray<MethodDeclarationSyntax> targets)
    {
        if (targets.Length == 0)
            return;

        if (targets.Length > 1)
        {
            spc.ReportDiagnostic(Diagnostic.Create(Unsupported, targets[1].GetLocation(),
                "more than one method is marked [InlineIntoPostfix]; there can be only one"));
            return;
        }

        var apply = targets[0];
        var bodies = new Dictionary<string, MethodDeclarationSyntax>();
        foreach (var method in inlinable)
            bodies[method.Identifier.ValueText] = method;

        if (apply.Body == null)
        {
            spc.ReportDiagnostic(Diagnostic.Create(Unsupported, apply.GetLocation(),
                "[InlineIntoPostfix] needs a block body; an expression-bodied method has no " +
                "statements to flatten"));
            return;
        }

        var inliner = new Inliner(bodies, spc);
        var flattened = inliner.Flatten(apply.Body);
        if (inliner.Failed)
            return;

        // The body moves from a method that returns int to one that assigns a ref parameter, and
        // it moves out of TickOffset into RNGPatches, so two things have to be rewritten: what a
        // return means, and what an unqualified name refers to.
        var owner = apply.Parent as TypeDeclarationSyntax;
        flattened = (BlockSyntax)new Qualifier(MemberNamesOf(owner), owner?.Identifier.ValueText)
            .Visit(flattened);
        flattened = (BlockSyntax)new ReturnRewriter().Visit(flattened);

        var rollParameter = apply.ParameterList.Parameters[0].Identifier.ValueText;
        var tickParameter = apply.ParameterList.Parameters[1].Identifier.ValueText;

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/> Flattened from TickOffset.Apply by RNGTick.Generator.");
        source.AppendLine("// Do not edit. Edit TickOffset instead; this file follows it.");
        source.AppendLine("#nullable enable");
        source.AppendLine("using Atomcraft;");
        source.AppendLine("using HarmonyLib;");
        source.AppendLine();
        source.AppendLine("namespace RNGTick;");
        source.AppendLine();
        source.AppendLine("partial class RNGPatches");
        source.AppendLine("{");
        source.AppendLine("    /// <summary>");
        source.AppendLine("    /// The offset, flat. Generated from <see cref=\"TickOffset.Apply\"/>; see");
        source.AppendLine("    /// RNGTick.Generator for why it is not simply a call to it.");
        source.AppendLine("    /// </summary>");
        source.AppendLine("    [HarmonyPostfix]");
        source.AppendLine("    public static void AfterRoll(int tick, ref int __result)");
        source.AppendLine("    {");
        source.AppendLine("        if (!RNG.IsInitialized)");
        source.AppendLine("            return;");
        source.AppendLine();
        source.AppendLine($"        var {rollParameter} = __result;");
        if (tickParameter != "tick")
            source.AppendLine($"        var {tickParameter} = tick;");
        source.AppendLine();

        foreach (var statement in flattened.Statements)
            source.AppendLine("        " + statement.NormalizeWhitespace("    ").ToFullString()
                .Replace("\n", "\n        ").TrimEnd());

        source.AppendLine("    }");
        source.AppendLine("}");

        spc.AddSource("RNGPatches.AfterRoll.g.cs", source.ToString());
    }

    /// <summary>
    /// Replaces calls to <c>[Inlinable]</c> methods with their bodies, to a fixed point.
    ///
    /// <para>Each call becomes: one local per parameter holding the argument, then the callee's
    /// statements with its parameter names rewritten to those locals, then the call site reading
    /// a local holding what the callee returned. That is what a compiler's inliner does, and it
    /// is why this does not simply paste expressions: substituting an argument textually would
    /// evaluate it once per use.</para>
    /// </summary>
    private sealed class Inliner
    {
        private readonly Dictionary<string, MethodDeclarationSyntax> _bodies;
        private readonly SourceProductionContext _spc;
        private int _temp;

        public bool Failed { get; private set; }

        public Inliner(Dictionary<string, MethodDeclarationSyntax> bodies, SourceProductionContext spc)
        {
            _bodies = bodies;
            _spc = spc;
        }

        public BlockSyntax Flatten(BlockSyntax block)
        {
            for (var pass = 0; pass < 16; pass++)
            {
                var statements = new List<StatementSyntax>();
                var changed = false;

                foreach (var statement in block.Statements)
                {
                    var rewritten = FlattenStatement(statement, statements, ref changed);
                    statements.Add(rewritten);
                }

                block = SyntaxFactory.Block(statements);
                if (!changed)
                    return block;
            }

            Fail(block, "inlining did not settle after 16 passes; is a method calling itself?");
            return block;
        }

        private StatementSyntax FlattenStatement(StatementSyntax statement,
            List<StatementSyntax> prelude, ref bool changed)
        {
            // Nested blocks first, so an if's body is flattened with its own prelude inside it
            // rather than hoisted out past the condition that guards it.
            if (statement is IfStatementSyntax ifStatement)
            {
                var inner = ifStatement.Statement is BlockSyntax b
                    ? Flatten(b)
                    : Flatten(SyntaxFactory.Block(ifStatement.Statement));
                statement = ifStatement.WithStatement(inner);
            }

            while (true)
            {
                var call = statement.DescendantNodes()
                    .OfType<InvocationExpressionSyntax>()
                    .FirstOrDefault(IsInlinable);
                if (call == null)
                    return statement;

                changed = true;
                var name = NameOf(call)!;
                var callee = _bodies[name];
                var slot = $"__inl{_temp++}";

                var arguments = call.ArgumentList.Arguments;
                if (arguments.Count != callee.ParameterList.Parameters.Count)
                {
                    Fail(call, $"call to '{name}' has {arguments.Count} arguments for " +
                               $"{callee.ParameterList.Parameters.Count} parameters");
                    return statement;
                }

                var renames = new Dictionary<string, string>();
                for (var i = 0; i < arguments.Count; i++)
                {
                    var parameter = callee.ParameterList.Parameters[i];
                    var local = $"{slot}_{parameter.Identifier.ValueText}";
                    renames[parameter.Identifier.ValueText] = local;
                    prelude.Add(SyntaxFactory.ParseStatement(
                        $"{parameter.Type} {local} = {arguments[i].Expression};"));
                }

                prelude.Add(SyntaxFactory.ParseStatement($"{callee.ReturnType} {slot};"));

                if (!SpliceBody(callee, renames, slot, prelude, name))
                    return statement;

                statement = statement.ReplaceNode(call, SyntaxFactory.IdentifierName(slot));
            }
        }

        /// <summary>Appends the callee's statements, with its return assigning to the slot.</summary>
        private bool SpliceBody(MethodDeclarationSyntax callee, Dictionary<string, string> renames,
            string slot, List<StatementSyntax> prelude, string name)
        {
            var rename = new Renamer(renames);

            if (callee.ExpressionBody != null)
            {
                var expression = (ExpressionSyntax)rename.Visit(callee.ExpressionBody.Expression);
                prelude.Add(SyntaxFactory.ParseStatement($"{slot} = {expression};"));
                return true;
            }

            if (callee.Body == null)
            {
                Fail(callee, $"'{name}' is marked [Inlinable] but has no body");
                return false;
            }

            if (SpliceStatements(callee.Body.Statements, rename, slot, prelude, callee, name))
                return true;

            Fail(callee, $"'{name}' has no return statement");
            return false;
        }

        /// <summary>
        /// Copies a callee's statements, turning its <c>return</c> into an assignment to the slot.
        ///
        /// <para>Recurses through <c>checked</c> and <c>unchecked</c> blocks and puts the same
        /// wrapper back around what it produces. That is not cosmetic: the hash in
        /// <c>TickOffset.Mix</c> is entirely inside an <c>unchecked</c> block because it relies on
        /// multiplication wrapping, and splicing its statements out of that context would change
        /// the arithmetic in any project that turns overflow checking on.</para>
        /// </summary>
        private bool SpliceStatements(SyntaxList<StatementSyntax> statements, Renamer rename,
            string slot, List<StatementSyntax> output, MethodDeclarationSyntax callee, string name)
        {
            for (var i = 0; i < statements.Count; i++)
            {
                var statement = (StatementSyntax)rename.Visit(statements[i]);

                if (statement is ReturnStatementSyntax returnStatement)
                {
                    if (i != statements.Count - 1)
                    {
                        Fail(callee, $"'{name}' returns before its last statement; this generator " +
                                     "only inlines methods with a single trailing return");
                        return false;
                    }

                    output.Add(SyntaxFactory.ParseStatement($"{slot} = {returnStatement.Expression};"));
                    return true;
                }

                if (statement is CheckedStatementSyntax checkedStatement)
                {
                    var inner = new List<StatementSyntax>();
                    var returned = SpliceStatements(checkedStatement.Block.Statements, rename, slot,
                        inner, callee, name);
                    output.Add(checkedStatement.WithBlock(SyntaxFactory.Block(inner)));
                    if (returned)
                        return true;
                    continue;
                }

                output.Add(statement);
            }

            return false;
        }

        private bool IsInlinable(InvocationExpressionSyntax call) =>
            NameOf(call) is { } name && _bodies.ContainsKey(name);

        private static string? NameOf(InvocationExpressionSyntax call) => call.Expression switch
        {
            IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
            MemberAccessExpressionSyntax member => member.Name.Identifier.ValueText,
            _ => null,
        };

        private void Fail(SyntaxNode node, string message)
        {
            Failed = true;
            // Synthesized nodes have no place in any source file, and Roslyn refuses a diagnostic
            // pointing at one. Falling back to no location keeps the message rather than turning
            // it into an ArgumentException out of the generator.
            var location = node.SyntaxTree.FilePath.Length > 0 ? node.GetLocation() : Location.None;
            _spc.ReportDiagnostic(Diagnostic.Create(Unsupported, location, message));
        }
    }

    /// <summary>Member names declared on the type the body is being moved out of.</summary>
    private static HashSet<string> MemberNamesOf(TypeDeclarationSyntax? type)
    {
        var names = new HashSet<string>();
        if (type == null)
            return names;

        foreach (var member in type.Members)
        {
            switch (member)
            {
                case MethodDeclarationSyntax method:
                    names.Add(method.Identifier.ValueText);
                    break;
                case PropertyDeclarationSyntax property:
                    names.Add(property.Identifier.ValueText);
                    break;
                case FieldDeclarationSyntax field:
                    foreach (var variable in field.Declaration.Variables)
                        names.Add(variable.Identifier.ValueText);
                    break;
            }
        }

        return names;
    }

    /// <summary>
    /// Qualifies bare references to the original type's members, which stop resolving once the
    /// body is emitted into another class.
    ///
    /// <para>Syntactic, not semantic: any bare identifier matching a member name is qualified.
    /// That is safe here because the locals this generator introduces are all prefixed, and a
    /// local shadowing a member name would be caught by the compiler rather than silently
    /// mis-bound -- <c>TickOffset.sum</c> does not exist.</para>
    /// </summary>
    private sealed class Qualifier : CSharpSyntaxRewriter
    {
        private readonly HashSet<string> _members;
        private readonly string? _owner;

        public Qualifier(HashSet<string> members, string? owner)
        {
            _members = members;
            _owner = owner;
        }

        public override SyntaxNode? VisitIdentifierName(IdentifierNameSyntax node)
        {
            if (_owner == null || !_members.Contains(node.Identifier.ValueText))
                return node;

            // Already qualified as something.Member: leave it alone.
            if (node.Parent is MemberAccessExpressionSyntax access && access.Name == node)
                return node;

            return SyntaxFactory.ParseExpression($"{_owner}.{node.Identifier.ValueText}")
                .WithTriviaFrom(node);
        }
    }

    /// <summary>Turns <c>return x;</c> into an assignment to the postfix's ref result.</summary>
    private sealed class ReturnRewriter : CSharpSyntaxRewriter
    {
        public override SyntaxNode VisitReturnStatement(ReturnStatementSyntax node) =>
            node.Expression == null
                ? node
                : SyntaxFactory.ParseStatement($"{{ __result = {node.Expression}; return; }}");
    }

    /// <summary>Rewrites a callee's parameter names to the locals holding its arguments.</summary>
    private sealed class Renamer : CSharpSyntaxRewriter
    {
        private readonly Dictionary<string, string> _renames;

        public Renamer(Dictionary<string, string> renames) => _renames = renames;

        public override SyntaxNode VisitIdentifierName(IdentifierNameSyntax node) =>
            _renames.TryGetValue(node.Identifier.ValueText, out var replacement)
                ? SyntaxFactory.IdentifierName(replacement).WithTriviaFrom(node)
                : node;
    }
}
